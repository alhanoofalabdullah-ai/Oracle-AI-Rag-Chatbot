## Order Items

CREATE TABLE api_order_items (

    order_item_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    order_id NUMBER
        NOT NULL,

    product_id NUMBER
        NOT NULL,

    quantity NUMBER
        NOT NULL,

    unit_price NUMBER(12,2)
        NOT NULL,

    line_total NUMBER(14,2)
        NOT NULL,

    CONSTRAINT pk_api_order_items
        PRIMARY KEY (order_item_id),

    CONSTRAINT fk_item_order
        FOREIGN KEY (order_id)
        REFERENCES api_orders(order_id),

    CONSTRAINT fk_item_product
        FOREIGN KEY (product_id)
        REFERENCES api_products(product_id),

    CONSTRAINT chk_item_quantity
        CHECK (quantity > 0),

    CONSTRAINT chk_item_price
        CHECK (unit_price >= 0)
);

