## Customers

CREATE TABLE api_customers (

    customer_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    customer_code VARCHAR2(50)
        NOT NULL,

    customer_name VARCHAR2(200)
        NOT NULL,

    email VARCHAR2(320)
        NOT NULL,

    phone VARCHAR2(50),

    status VARCHAR2(20)
        DEFAULT 'ACTIVE'
        NOT NULL,

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP,

    updated_at TIMESTAMP
        DEFAULT SYSTIMESTAMP,

    CONSTRAINT pk_api_customers
        PRIMARY KEY (customer_id),

    CONSTRAINT uq_api_customer_code
        UNIQUE (customer_code),

    CONSTRAINT uq_api_customer_email
        UNIQUE (email),

    CONSTRAINT chk_customer_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE',
                'SUSPENDED'
            )
        )
);

