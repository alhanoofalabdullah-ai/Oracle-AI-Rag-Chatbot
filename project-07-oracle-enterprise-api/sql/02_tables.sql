## API Error Log

CREATE TABLE api_error_log (

    error_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    request_id VARCHAR2(100),

    error_code VARCHAR2(100),

    error_message VARCHAR2(4000),

    stack_trace CLOB,

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP,

