## Orders

CREATE TABLE api_orders (

    order_id NUMBER
        GENERATED BY DEFAULT AS IDENTITY,

    order_number VARCHAR2(50)
        NOT NULL,

    customer_id NUMBER
        NOT NULL,

    order_status VARCHAR2(30)
        DEFAULT 'PENDING',

    total_amount NUMBER(14,2)
        DEFAULT 0,

    created_at TIMESTAMP
        DEFAULT SYSTIMESTAMP,

    updated_at TIMESTAMP
        DEFAULT SYSTIMESTAMP,

    CONSTRAINT pk_api_orders
        PRIMARY KEY (order_id),

    CONSTRAINT uq_order_number
        UNIQUE (order_number),

    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)
        REFERENCES api_customers(customer_id)
);

